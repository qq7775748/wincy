#!/usr/bin/env python3
"""Generate src/pinyin-data.js for pinyin search.

Emits two compact maps over the GB2312 hanzi set (6763 chars — everything a
clipboard normally carries):

  TEECY_PY     syllable -> concatenated hanzi whose PRIMARY reading is that
               syllable. Reversed at load time into char -> pinyin.
  TEECY_PY_ALT char -> list of additional (non-primary) readings, for
               heteronyms like 行(xing/hang) or 重(zhong/chong).

Only single characters are indexed; phrase tables are unnecessary because
matching walks the text character by character.
"""

import io
import json
import os

from pypinyin import pinyin_dict
from pypinyin.contrib.tone_convert import to_normal


def gb2312_hanzi():
    """GB2312 level-1 + level-2 hanzi (6763 chars)."""
    out = []
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                out.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return out


def build():
    # Read straight from pypinyin's static char table. Calling pinyin() per
    # character turned out to be flaky: with heteronym=True the first calls
    # return every reading, then results silently degrade to one reading.
    # The table below is inert data — no state, no surprises.
    table = pinyin_dict.pinyin_dict
    buckets = {}
    alt = {}
    for ch in gb2312_hanzi():
        raw = table.get(ord(ch))
        if not raw:
            continue
        readings = []
        for toned in raw.split(","):
            plain = to_normal(toned)
            if plain and plain.isalpha() and plain not in readings:
                readings.append(plain)
        if not readings:
            continue
        buckets.setdefault(readings[0], []).append(ch)
        if len(readings) > 1:
            alt[ch] = readings[1:]

    ordered = {k: "".join(v) for k, v in sorted(buckets.items())}
    total = sum(len(v) for v in ordered.values())
    head = (
        "// Generated by tools/gen_pinyin.py — do not edit.\n"
        f"// {total} hanzi in {len(ordered)} syllables, {len(alt)} heteronyms.\n"
    )
    body = (
        "window.TEECY_PY="
        + json.dumps(ordered, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
        "window.TEECY_PY_ALT="
        + json.dumps(alt, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    return head + body, total, len(ordered), len(alt)


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(root, "src", "pinyin-data.js")
    text, total, syllables, heteronyms = build()
    with io.open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(
        f"{out_path}: {total} hanzi / {syllables} syllables / "
        f"{heteronyms} heteronyms, {len(text.encode('utf-8'))} bytes"
    )
